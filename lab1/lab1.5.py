a = float(input("Введите число a:"))
b = float(input("Введите число b:"))
print("Сумма:", a + b)
print("Разность:", a - b)
print("Произведение:", a * b)
if b == 0:
    print("Частное: делить на ноль нельзя")
    print("Остаток: делить на ноль нельзя")
else:
    print("Частное:", a / b)
    print("Остаток:", a % b)
print("Степень:", a ** b)