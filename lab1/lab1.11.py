age = int(input("Возраст: "))
d = float(input("Ежемесячный доход: "))
sum = float(input("Размер кредита: "))
months = int(input("Срок кредита (мес): "))
his = input("Кредитная история (отличная/хорошая/удовлетворительная/плохая): ")
por = input("Есть поручители? (да/нет): ")
zal = input("Есть залог? (да/нет): ")

print ("Соотношение кредита к доходу:", sum / d)
risk = 0
if (age < 25) or (age > 60):
    risk += 1
else: risk -= 1

if sum / months > d:
     risk += 1
else: risk -= 1

if his == "отличная":
    risk -= 2
elif his == "хорошая":
    risk -= 1
elif his == "плохая":
    risk += 2

if por == 'да':
    risk -= 2
else: risk += 1

if zal == 'да':
    risk -= 2
else: risk += 1

if risk <= -6:
    print("Низеий риск, ставка - 12%, рекомендации - одобрить")
elif risk <= -3:
    print("Средний риск, ставка - 16%, рекомендации - одобрить с осторожностью")
elif risk <= 0:
    print("Высокий риск, ставка - 22%, рекомендации - cкорее отклонить")
else:
    print("Критический риск, ставка - 30%, рекомендации - отклонить")